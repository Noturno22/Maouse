class _I18n(QObject):
    language_changed = Signal(str)

    LANGS = LANGS
    NATIVE = NATIVE

    def __init__(self):
        super().__init__()
        self._lang = PT

    @property
    def lang(self):
        return self._lang

    def native(self, code):
        return NATIVE.get(code, NATIVE[PT])

    def set_lang(self, lang):
        if lang not in LANGS or lang == self._lang:
            return False
        self._lang = lang
        self.language_changed.emit(lang)
        return True

    def toggle(self):
        """Cicla pelo idioma seguinte na ordem de LANGS (compat)."""
        idx = (LANGS.index(self._lang) + 1) % len(LANGS)
        self.set_lang(LANGS[idx])
        return self._lang

    def tr(self, key):
        table = _STRINGS.get(key)
        if not table:
            return key
        return table.get(self._lang, table[PT])


I18N = _I18n()


def tr(key):
    return I18N.tr(key)
